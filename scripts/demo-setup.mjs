import fs from 'node:fs';
import path from 'node:path';
import os from 'node:os';
import crypto from 'node:crypto';
import {fileURLToPath} from 'node:url';
import {spawnSync,spawn} from 'node:child_process';

const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const runtime=path.resolve(process.env.CRM_RUNTIME_DIR||(process.platform==='win32'&&fs.existsSync('D:/')?'D:/CRM-local/showcase':path.join(os.homedir(),'.bizpulse-demo')));
const data=path.join(runtime,'supabase-demo');
const envFile=path.join(data,'compose.env');
const appEnv=path.join(root,'.env.local');
const marker=path.join(data,'baseline-applied');
const args=process.argv.slice(2);
function run(exe,argv,options={}){
  const result=spawnSync(exe,argv,{cwd:root,windowsHide:true,encoding:'utf8',...options});
  if(result.error||result.status!==0)throw Error(`步骤失败：${exe} ${argv[0]||''}。请检查 Docker、端口和运行目录权限；原有配置与数据未重置。`);
  return result.stdout;
}
const composeArgs=['compose','--project-name','bizpulse-showcase-demo','--env-file',envFile,'-f',path.join(root,'infra/demo/compose.yml')];
const compose=(argv,options)=>run('docker',[...composeArgs,...argv],options);
const secret=()=>crypto.randomBytes(32).toString('hex');
const jwt=(role,key)=>{
  const encoded=value=>Buffer.from(JSON.stringify(value)).toString('base64url');
  const input=`${encoded({alg:'HS256',typ:'JWT'})}.${encoded({role,iss:'supabase-demo',iat:Math.floor(Date.now()/1000),exp:Math.floor(Date.now()/1000)+315360000})}`;
  return `${input}.${crypto.createHmac('sha256',key).update(input).digest('base64url')}`;
};
function readEnv(file){return Object.fromEntries(fs.readFileSync(file,'utf8').split(/\r?\n/).filter(line=>line&&!line.startsWith('#')).map(line=>{const i=line.indexOf('=');return [line.slice(0,i),line.slice(i+1)];}));}
const sleep=ms=>new Promise(resolve=>setTimeout(resolve,ms));
async function waitFor(url){for(let i=0;i<90;i++){try{if((await fetch(url,{signal:AbortSignal.timeout(2000)})).ok)return;}catch{}await sleep(1000);}throw Error('本地 Supabase 启动超时。使用文档中的 compose logs 命令检查，不要删除数据目录。');}
async function main(){
  fs.mkdirSync(data,{recursive:true});
  if(args.includes('--down')){if(!fs.existsSync(envFile))throw Error('没有此演示栈的配置。');compose(['down']);console.info('演示容器已停止，数据库与配置保留。Node 网关继续监听 loopback，供下次复用。');return;}
  if(fs.existsSync(appEnv)&&!fs.readFileSync(appEnv,'utf8').startsWith('# Generated by demo-setup.mjs\n'))throw Error('已有 .env.local；为保护现有 CRM，请在独立 clone 中执行。不会覆盖该文件。');
  if(!fs.existsSync(envFile)){
    const key=secret();
    fs.writeFileSync(envFile,Object.entries({CRM_DEMO_DATA_DIR:data.replaceAll('\\','/'),POSTGRES_PASSWORD:secret(),JWT_SECRET:key,ANON_KEY:jwt('anon',key),SERVICE_ROLE_KEY:jwt('service_role',key),OWNER_EMAIL:'owner@example.invalid',OWNER_PASSWORD:secret(),INTERNAL_SECRET:secret(),AI_CRED_AES_KEY:crypto.randomBytes(32).toString('base64')}).map(([k,v])=>`${k}=${v}`).join('\n')+'\n',{mode:0o600});
  }
  const env=readEnv(envFile);
  if(path.resolve(env.CRM_DEMO_DATA_DIR)!==data)throw Error('运行目录与已有配置不一致。请复用相同 CRM_RUNTIME_DIR。');
  fs.mkdirSync(path.join(data,'db'),{recursive:true});fs.mkdirSync(path.join(data,'storage'),{recursive:true});
  // Do not print `compose config`: it expands secrets into its output.
  if(args.includes('--pull'))compose(['pull']);
  compose(['up','-d','--pull','never']);
  await waitFor('http://127.0.0.1:54342/health');
  await waitFor('http://127.0.0.1:54344/status');
  if(!fs.existsSync(marker)){
    console.info('首次安装：应用仓库 canonical baseline（仅新的独立演示数据库）。');
    compose(['exec','-T','db','psql','-U','postgres','-d','postgres','-v','ON_ERROR_STOP=1'],{input:fs.readFileSync(path.join(root,'supabase/baseline.sql'),'utf8'),maxBuffer:32*1024*1024});
    fs.writeFileSync(marker,new Date().toISOString());
  }
  compose(['exec','-T','db','psql','-U','postgres','-d','postgres','-c',"NOTIFY pgrst, 'reload schema';"]);
  let gatewayReady=false;
  try{gatewayReady=(await (await fetch('http://127.0.0.1:54340/health',{signal:AbortSignal.timeout(1000)})).text())==='crm-demo-gateway-v1';}catch{}
  if(!gatewayReady){
    const log=fs.openSync(path.join(data,'gateway.log'),'a');
    const child=spawn(process.execPath,[path.join(root,'infra/demo/gateway.mjs')],{detached:true,stdio:['ignore',log,log],windowsHide:true});child.unref();fs.closeSync(log);
    await waitFor('http://127.0.0.1:54340/health');
  }
  const configuration={NEXT_PUBLIC_SUPABASE_URL:'http://127.0.0.1:54340',NEXT_PUBLIC_SUPABASE_ANON_KEY:env.ANON_KEY,SUPABASE_SERVICE_ROLE_KEY:env.SERVICE_ROLE_KEY,SUPABASE_DB_URL:`postgresql://postgres:${env.POSTGRES_PASSWORD}@127.0.0.1:54341/postgres`,NEXT_PUBLIC_APP_URL:'http://localhost:54349',CRM_DEMO_MODE:'true',CRM_REALTIME_ENABLED:'false',CRM_DEMO_EMAIL:'demo@example.invalid',CRM_DEMO_PASSWORD:env.OWNER_PASSWORD,OWNER_EMAIL:env.OWNER_EMAIL,OWNER_PASSWORD:env.OWNER_PASSWORD,OWNER_ORG_NAME:'Showcase Admin',APP_LOCALE:'pt-BR',INTERNAL_SECRET:env.INTERNAL_SECRET,AI_CRED_AES_KEY:env.AI_CRED_AES_KEY};
  fs.writeFileSync(appEnv,'# Generated by demo-setup.mjs\n'+Object.entries(configuration).map(([k,v])=>`${k}=${v}`).join('\n')+'\n',{mode:0o600});
  const tsx=path.join(root,'node_modules/tsx/dist/cli.mjs');
  if(!fs.existsSync(tsx))throw Error('Supabase 与配置已准备；请先 pnpm install --frozen-lockfile，再重新执行 setup 来创建管理员。');
  run(process.execPath,[tsx,'--env-file=.env.local','scripts/bootstrap-owner.ts'],{env:{...process.env,...configuration}});
  console.info(`独立演示 Supabase 和管理员已准备。密钥仅保存在 ${envFile} 与 .env.local，未输出。\n首次 pnpm demo 会创建虚构数据并编译；后续复用数据与构建。\n使用相同 CRM_RUNTIME_DIR，运行 pnpm demo -- --port=54349。`);
}
main().catch(error=>{console.error(error.message);process.exitCode=1;});
